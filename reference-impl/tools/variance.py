"""Aggregate repeated imitation runs per condition: mean / min / max of each measure.

GENERATED output; says how much runs of the SAME condition differ, so a
between-condition gap can be read against it. Looks are judged by the user.

Phase values are circular (period from measure.json); they are averaged as
angles, and min/max are reported as offsets from that circular mean.

Usage:
    python -X utf8 tools/variance.py --out experiments/r2-c05-repeat/variance.md \
        --group "A=experiments/r1-c05/A,experiments/r2-c05-repeat/A2,experiments/r2-c05-repeat/A3" \
        --group "B=experiments/r2-c05-repeat/B2,experiments/r2-c05-repeat/B3"
    python -X utf8 tools/variance.py --selftest
"""
import argparse
import json
import math
from pathlib import Path

LINEAR = [
    ("動作峰值鎖拍 R", ("phase_lock_motion_peaks", "R")),
    ("動作峰值離散 ms", ("phase_lock_motion_peaks", "spread_ms")),
    ("動作峰值數 n", ("phase_lock_motion_peaks", "n")),
    ("形變起點鎖拍 R", ("phase_lock_move_starts", "R")),
    ("ζ 中位數", ("zeta_median",)),
    ("ω 中位數 rad/s", ("omega_median",)),
    ("最大回彈", ("overshoot_max",)),
    ("首尾幀差", ("loop_first_last_mean_abs_diff",)),
    ("剪接點", ("cuts",)),
]
CIRCULAR = [
    ("動作峰值平均相位 ms", "phase_lock_motion_peaks"),
    ("形變起點平均相位 ms", "phase_lock_move_starts"),
]


def get(d, keys):
    for k in keys:
        d = d.get(k) if isinstance(d, dict) else None
    return d


def circ_stats(phases_ms, period_ms):
    ang = [2 * math.pi * p / period_ms for p in phases_ms]
    c = sum(math.cos(a) for a in ang) / len(ang)
    s = sum(math.sin(a) for a in ang) / len(ang)
    mean = math.atan2(s, c) * period_ms / (2 * math.pi)
    offs = [((p - mean + period_ms / 2) % period_ms) - period_ms / 2 for p in phases_ms]
    return mean, mean + min(offs), mean + max(offs)


def stats(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return None
    return sum(vals) / len(vals), min(vals), max(vals)


def fmt(t, nd=3):
    if t is None:
        return "—"
    m, lo, hi = t
    return f"{m:.{nd}g}（{lo:.{nd}g} ~ {hi:.{nd}g}）"


def summarise(groups):
    """groups: {name: [measure dicts]} -> {name: {label: (mean, lo, hi)}}"""
    res = {}
    for g, ms in groups.items():
        row = {"runs n": (len(ms), len(ms), len(ms))}
        for label, keys in LINEAR:
            row[label] = stats([get(m, keys) for m in ms])
        for label, key in CIRCULAR:
            ph = [(get(m, (key, "mean_phase_ms")), get(m, (key, "period_s"))) for m in ms]
            ph = [(p, per) for p, per in ph if p is not None]
            row[label] = circ_stats([p for p, _ in ph], ph[0][1] * 1000) if ph else None
        res[g] = row
    return res


def selftest():
    # known-true: phases +240 and -240 at 500 ms period straddle the wrap; circular mean must be ~250, not 0
    m, lo, hi = circ_stats([240, -240], 500)
    assert abs(abs(m) - 250) < 1e-6 and abs(hi - lo - 20) < 1e-6, (m, lo, hi)
    # known-false for a naive linear mean: +60 and -3 must give 28.5 either way
    m, lo, hi = circ_stats([60, -3], 500)
    assert abs(m - 28.5) < 0.5 and abs(lo + 3) < 0.5 and abs(hi - 60) < 0.5, (m, lo, hi)
    r = summarise({"X": [{"omega_median": 10, "phase_lock_motion_peaks": {"mean_phase_ms": 0, "period_s": 0.5, "R": 1}},
                         {"omega_median": 20, "phase_lock_motion_peaks": {"mean_phase_ms": 10, "period_s": 0.5, "R": 0.5}}]})
    assert r["X"]["ω 中位數 rad/s"] == (15, 10, 20)
    assert r["X"]["動作峰值鎖拍 R"] == (0.75, 0.5, 1)
    print("variance selftest PASS")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--group", action="append", default=[])
    ap.add_argument("--out")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    groups, members = {}, {}
    for spec in a.group:
        name, paths = spec.split("=", 1)
        members[name] = [p.strip() for p in paths.split(",")]
        groups[name] = [json.loads((Path(p) / "measure.json").read_text(encoding="utf-8"))
                        for p in members[name] if (Path(p) / "measure.json").exists()]
    res = summarise(groups)
    names = list(res)
    labels = list(next(iter(res.values())).keys())
    lines = ["<!-- GENERATED by tools/variance.py. Looks are judged by the user, not by this table. -->",
             "# 同條件多次執行的變異", "",
             "每格是「平均（最小 ~ 最大）」。相位用圓周平均（週期 = 一拍）。", "",
             "| 項目 | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for lab in labels:
        nd = 2 if lab == "runs n" else 3
        cells = [f"{res[n][lab][0]}" if lab == "runs n" else fmt(res[n][lab], nd) for n in names]
        lines.append(f"| {lab} | " + " | ".join(cells) + " |")
    lines += ["", "組成："] + [f"- {n}：" + "、".join(f"`{p}`" for p in members[n]) for n in names]
    text = "\n".join(lines) + "\n"
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
