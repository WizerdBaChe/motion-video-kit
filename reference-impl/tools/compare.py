"""Build experiments/<round>/compare.md from each column's measure.json + run.json.

GENERATED output; the verdict on looks is the user's, not this table's.

Usage:
    python -X utf8 tools/compare.py experiments/r1-c05 original A B
"""
import json
import sys
from pathlib import Path


def get(d, *keys):
    for k in keys:
        if d is None:
            return None
        d = d.get(k) if isinstance(d, dict) else None
    return d


def fmt(v):
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def main():
    rd = Path(sys.argv[1])
    cols = sys.argv[2:]
    m, r = {}, {}
    for c in cols:
        mp = rd / c / "measure.json"
        m[c] = json.loads(mp.read_text(encoding="utf-8")) if mp.exists() else None
        rp = rd / c / "run.json"
        r[c] = json.loads(rp.read_text(encoding="utf-8")) if rp.exists() else None
    rows = [
        ("狀態", lambda c: get(r[c], "status") or ("原片" if c == "original" else None)),
        ("花費 USD", lambda c: get(r[c], "cost_usd")),
        ("生成時間 s", lambda c: get(r[c], "seconds")),
        ("長度 s", lambda c: get(m[c], "duration_s")),
        ("fps / 尺寸", lambda c: m[c] and f"{m[c]['fps']:g} / {m[c]['size']}"),
        ("剪接點（應為 0）", lambda c: get(m[c], "cuts")),
        ("首尾幀差（越小越能循環）", lambda c: get(m[c], "loop_first_last_mean_abs_diff")),
        ("拍點格線來源", lambda c: get(m[c], "grid_used")),
        ("形變起點鎖拍 R", lambda c: get(m[c], "phase_lock_move_starts", "R")),
        ("形變起點平均相位 ms", lambda c: get(m[c], "phase_lock_move_starts", "mean_phase_ms")),
        ("動作峰值鎖拍 R", lambda c: get(m[c], "phase_lock_motion_peaks", "R")),
        ("動作峰值平均相位 ms", lambda c: get(m[c], "phase_lock_motion_peaks", "mean_phase_ms")),
        ("可信彈簧擬合數 / 總數", lambda c: m[c] and f"{m[c]['springs_consistent_n']} / {m[c]['springs_total_n']}"),
        ("ζ 中位數", lambda c: get(m[c], "zeta_median")),
        ("ω 中位數 rad/s", lambda c: get(m[c], "omega_median")),
        ("最大回彈", lambda c: get(m[c], "overshoot_max")),
        ("指示器前後緣 ω（左／右）", lambda c: m[c] and "; ".join(
            f"{p['omega_left']}/{p['omega_right']}" for p in m[c]["indicator_edge_pairs"]) or None),
    ]
    lines = ["<!-- GENERATED by tools/compare.py. Looks are judged by the user, not by this table. -->",
             f"# {rd.name} 比較表", "",
             "| 項目 | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for label, fn in rows:
        lines.append(f"| {label} | " + " | ".join(fmt(fn(c)) for c in cols) + " |")
    lines += ["", "原片的拍點格線是從音訊估計的（有半拍歧義，見 T01）；模仿組用合成音軌的已知拍點。"]
    (rd / "compare.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
