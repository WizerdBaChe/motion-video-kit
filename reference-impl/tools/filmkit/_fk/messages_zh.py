SECONDS_RE = r"(?<=\d) s\b"


def zh(text) -> str:
    if text is None:
        return "—"
    import re
    s = str(text)
    for pat, rep in REGEXES:
        s = re.sub(pat, rep, s, flags=re.S)
    for en, z in PHRASES:
        s = s.replace(en, z)
    return re.sub(SECONDS_RE, " 秒", s)
